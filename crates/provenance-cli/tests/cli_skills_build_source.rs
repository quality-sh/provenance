//! Implementation aid: the build script chooses the bundled skill sources.
//! A workspace build reads only the root sources; a packaged crate reads its own copies.

#[path = "../build/skills.rs"]
mod skills;

use std::path::Path;

/// The bundled skill names, read from the repository's root sources.
fn names() -> Vec<String> {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../skills");
    let mut names = std::fs::read_dir(root)
        .unwrap()
        .map(|entry| entry.unwrap().file_name().into_string().unwrap())
        .collect::<Vec<_>>();
    names.sort();
    names
}

fn write_skills(root: &Path, text: &str, skip: Option<&str>) {
    for name in names().iter().filter(|name| Some(name.as_str()) != skip) {
        std::fs::create_dir_all(root.join(name)).unwrap();
        std::fs::write(root.join(name).join("SKILL.md"), format!("{text} {name}\n")).unwrap();
    }
}

fn read_output(output: &Path, name: &str) -> String {
    std::fs::read_to_string(output.join("skills").join(name).join("SKILL.md")).unwrap()
}

fn workspace() -> (tempfile::TempDir, std::path::PathBuf) {
    let temporary = tempfile::tempdir().unwrap();
    let crate_root = temporary.path().join("crates/provenance-cli");
    std::fs::create_dir_all(&crate_root).unwrap();
    std::fs::write(crate_root.join("Cargo.toml"), "[package]\n").unwrap();
    // Crate-local copies must not replace a missing root source.
    write_skills(&crate_root.join("skills"), "crate-local", None);
    (temporary, crate_root)
}

#[test]
fn workspace_build_fails_when_a_root_skill_source_is_missing() {
    let (temporary, crate_root) = workspace();
    write_skills(
        &temporary.path().join("skills"),
        "root",
        Some("provenance-shaping"),
    );
    let output = tempfile::tempdir().unwrap();
    let error = skills::generate(&crate_root, output.path()).unwrap_err();
    assert!(
        error.to_string().contains("provenance-shaping"),
        "unexpected error: {error}"
    );
}

#[test]
fn workspace_build_fails_when_the_root_skill_directory_is_missing() {
    let (_temporary, crate_root) = workspace();
    let output = tempfile::tempdir().unwrap();
    let error = skills::generate(&crate_root, output.path()).unwrap_err();
    assert!(
        error
            .to_string()
            .contains("workspace skill sources are missing"),
        "unexpected error: {error}"
    );
}

#[test]
fn workspace_build_with_a_stray_manifest_backup_reads_the_root_sources() {
    let (temporary, crate_root) = workspace();
    // A merge tool can leave this backup in a workspace.
    std::fs::write(crate_root.join("Cargo.toml.orig"), "[package]\n").unwrap();
    write_skills(&temporary.path().join("skills"), "root", None);
    let output = tempfile::tempdir().unwrap();
    skills::generate(&crate_root, output.path()).unwrap();
    for name in names() {
        assert_eq!(read_output(output.path(), &name), format!("root {name}\n"));
    }
    std::fs::remove_file(temporary.path().join("skills/provenance-shaping/SKILL.md")).unwrap();
    let error = skills::generate(&crate_root, tempfile::tempdir().unwrap().path()).unwrap_err();
    assert!(
        error.to_string().contains("provenance-shaping"),
        "unexpected error: {error}"
    );
}

#[test]
fn packaged_crate_reads_its_own_skill_copies() {
    let (_temporary, crate_root) = workspace();
    std::fs::write(
        crate_root.join("Cargo.toml"),
        "# THIS FILE IS AUTOMATICALLY GENERATED BY CARGO\n#\n[package]\n",
    )
    .unwrap();
    let output = tempfile::tempdir().unwrap();
    skills::generate(&crate_root, output.path()).unwrap();
    for name in names() {
        assert_eq!(
            read_output(output.path(), &name),
            format!("crate-local {name}\n")
        );
    }
}
