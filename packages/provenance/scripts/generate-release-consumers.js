import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const defaults = {
  targets: fileURLToPath(new URL("../../../.github/release-targets.json", import.meta.url)),
  package: fileURLToPath(new URL("../package.json", import.meta.url)),
  runtime: fileURLToPath(new URL("../src/engine-packages.ts", import.meta.url)),
};
const { check, paths } = parseArgs(process.argv.slice(2));
const targets = JSON.parse(readFileSync(paths.targets, "utf8"));
const packageManifest = JSON.parse(readFileSync(paths.package, "utf8"));
const expectedDependencies = Object.fromEntries(
  targets.map((entry) => [entry.npm.name, packageManifest.version]),
);
const currentDependencies = packageManifest.optionalDependencies;
packageManifest.optionalDependencies = expectedDependencies;

const packageOutput = `${JSON.stringify(packageManifest, null, 2)}\n`;
const runtimeRows = targets.map((entry) => {
  const host = [entry.npm.os[0], entry.npm.cpu[0], entry.npm.libc?.[0]]
    .filter((part) => part !== undefined)
    .join("-");
  return `  [${JSON.stringify(host)}, ${JSON.stringify(entry.npm.name)}],`;
});
const runtimeOutput = [
  "// Generated by scripts/generate-release-consumers.js from .github/release-targets.json.",
  "// Do not edit this file directly.",
  "export const enginePackages: ReadonlyMap<string, string> = new Map([",
  ...runtimeRows,
  "]);",
  "",
].join("\n");

if (check) {
  if (sortedEntries(currentDependencies) !== sortedEntries(expectedDependencies)) {
    throw new Error(`generated release consumer is stale: ${paths.package}`);
  }
  if (readFileSync(paths.runtime, "utf8").replaceAll("\r\n", "\n") !== runtimeOutput) {
    throw new Error(`generated release consumer is stale: ${paths.runtime}`);
  }
} else {
  writeFileSync(paths.package, packageOutput);
  writeFileSync(paths.runtime, runtimeOutput);
}

function sortedEntries(value) {
  if (typeof value !== "object" || value === null || Array.isArray(value)) {
    return "";
  }
  return JSON.stringify(Object.entries(value).sort(([left], [right]) => left.localeCompare(right)));
}

function parseArgs(values) {
  const paths = { ...defaults };
  let check = false;
  for (let index = 0; index < values.length;) {
    if (values[index] === "--check") {
      check = true;
      index += 1;
      continue;
    }
    const flag = values[index];
    const value = values[index + 1];
    if (!flag?.startsWith("--") || value === undefined || !(flag.slice(2) in paths)) {
      throw new Error("arguments must be --check or --targets/--package/--runtime paths");
    }
    paths[flag.slice(2)] = value;
    index += 2;
  }
  return { check, paths };
}
